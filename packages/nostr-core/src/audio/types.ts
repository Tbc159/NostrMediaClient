import { estensioneDelNome, estensionePer } from '../media/extensions.js'
import type { MediaItem } from '../mediamanager/types.js'

/**
 * Audio processing: what the client can ask for, without saying whom.
 *
 * The media-manager's `audio` domain has replaced the previous service, and
 * with it its constraints: **the order of operations is free, formats do not
 * matter, and no operation destroys the source**. So there is no longer any
 * strategy to work out before asking: you send a reference and wait for a
 * job.
 *
 * The interface stays separate from the implementation because that is what
 * makes waiting for jobs testable without a network, not because another
 * service is expected.
 */

/** Formats the audio domain accepts as input and can produce. */
export type FormatoAudio = 'audio/mpeg' | 'audio/m4a' | 'audio/wav'

/**
 * A reference to a medium in the archive: the numeric id or the **filename**.
 *
 * The `filename` is generated by the service and has to be read back from the
 * response: the `title` you sent is not a valid reference.
 */
export type RiferimentoAudio = number | string

/** A file produced by a processing job. */
export interface MediaProdotto {
  id: number
  media_type: string
  content_url: string
  download_url: string
  /**
   * A URL for the bytes usable **without headers**, with an expiry.
   *
   * It is the only one that can go in an `<audio src>`: the browser does not
   * attach the key to subresource requests, and `content_url` gets a 401
   * there. It is missing if the service's environment has no signing key.
   */
  signed_url?: string
  signed_url_expires_at_s?: number
}

export interface OpzioniSilenzi {
  /**
   * Below this level it is silence, in decibels (for instance -40).
   *
   * A number and not a string: the unit is added by the service. It used to
   * have to be written by hand (`-40dB`), and omitting it meant passing a
   * linear amplitude, that is, cutting nothing with nothing saying so.
   */
  sogliaDb: number
  /** How long a pause has to be before it gets shortened, in seconds. */
  pausaMinimaS: number
  /** How much silence to leave: pauses are shortened, not zeroed. */
  silenzioDaLasciareS?: number
  /** The product's format. The service uses wav when nothing is said. */
  formato?: FormatoAudio
  titolo?: string
}

export interface OpzioniLivellamento {
  formato?: FormatoAudio
  titolo?: string
}

export interface StatoLavoro {
  stato: 'in-coda' | 'in-corso' | 'completato' | 'fallito'
  /** Present once the job is complete: the files produced, in order. */
  media?: MediaProdotto[]
  errore?: string
}

export interface ServizioAudio {
  readonly radice: string
  /** Whether the audio domain answers. */
  disponibile(): Promise<boolean>
  /** Sends the bytes to the archive. The reference to use afterwards is the `filename`. */
  carica(file: Blob, titolo: string, mime: FormatoAudio): Promise<MediaItem>
  /** Shortens the silences. Returns the job's identifier. */
  avviaSilenzi(sorgente: RiferimentoAudio, opzioni: OpzioniSilenzi): Promise<string>
  /** Levels the voices. Returns the job's identifier. */
  avviaLivellamento(sorgente: RiferimentoAudio, opzioni?: OpzioniLivellamento): Promise<string>
  /** Changes format. Returns the job's identifier. */
  avviaConversione(
    sorgente: RiferimentoAudio,
    formato: FormatoAudio,
    titolo?: string,
  ): Promise<string>
  stato(idLavoro: string): Promise<StatoLavoro>
  /** A product's bytes, to listen to it again or save it. */
  scarica(media: MediaProdotto): Promise<Blob>
}

/** A format's usual extension, to compose a file name. */
export function estensioneDi(formato: FormatoAudio): string {
  return estensionePer(formato) ?? 'bin'
}

/**
 * A file's format from its name, or `null` if it is not audio we can handle.
 *
 * `mp3` becomes `audio/mpeg`, which is the registered type: the service
 * accepts `audio/mp3` as an alias, but there is no reason to propagate a
 * wrong name.
 */
export function formatoDaNome(nome: string): FormatoAudio | null {
  const ext = estensioneDelNome(nome)
  if (ext === 'mp3') return 'audio/mpeg'
  if (ext === 'm4a') return 'audio/m4a'
  if (ext === 'wav') return 'audio/wav'
  return null
}
