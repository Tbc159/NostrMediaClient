/**
 * The media-manager microservice's types, traced from the OpenAPI contract.
 *
 * The source of truth is `openapi/<domain>/api.yaml` in the service's
 * repository: here we rewrite by hand only what the client really uses,
 * instead of generating everything. Today that is the archive (`media`),
 * which the audio processing uses to deposit sources and collect products;
 * image composition (`content`) lives on a branch of its own.
 */

/** A medium already uploaded to the service. */
export interface MediaItem {
  id: number
  /** The title **you sent**. It is not a valid reference. */
  title: string
  /**
   * The file name, **generated by the service**: this is the reference.
   *
   * The distinction is not pedantry: resolution by string looks only at
   * `filename`, and passing the `title` produces a 400. It has to be read
   * back from here, because it does not match what you sent.
   */
  filename: string
  media_type: string
  status?: 'ready' | 'processing' | 'error'
  size_bytes?: number | null
  duration_s?: number | null
  created_at_s?: number
  content_url?: string
  download_url?: string
  /**
   * A URL for the bytes usable **without headers**, with an expiry.
   *
   * It is the field for `<img src>` and `<audio src>`: the browser does not
   * attach the key to subresources, and `content_url` gets a 401 there.
   * Absent if the service's environment has no signing key; in that case the
   * bytes downloaded with the key are all there is.
   */
  signed_url?: string
  signed_url_expires_at_s?: number
}

export interface ElencoMedia {
  items: MediaItem[]
  page: number
  page_size: number
  total?: number
}
