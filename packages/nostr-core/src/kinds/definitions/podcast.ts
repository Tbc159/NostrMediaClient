/*
 * NIP-73 identifiers.
 *
 * An episode imported from another host keeps the GUID it had there, and a
 * show keeps its `podcast:guid`: every podcast app recognises episodes and
 * shows by those, so changing them would turn a move into a new podcast. NIP-73
 * already defines how a Nostr event names external content — an `i` tag with
 * the identifier and a `k` tag with its type — and Fountain uses the same
 * convention to tie Nostr comments and boosts to episodes. The feed service
 * reads them back as the RSS `<guid>` and `<podcast:guid>`.
 */
const PREFISSO_GUID_EPISODIO = 'podcast:item:guid:'
const PREFISSO_GUID_PODCAST = 'podcast:guid:'

function leggiIdentificatore(event: NostrEvent, prefisso: string): string | undefined {
  const tag = tagsNamed(event, 'i').find((t) => t[1]?.startsWith(prefisso))
  const valore = tag?.[1]?.slice(prefisso.length)
  return valore ? valore : undefined
}

function tagIdentificatore(prefisso: string, valore: string | undefined, tipo: string): Tag[] {
  if (valore === undefined) return []
  const pulito = valore.trim()
  if (pulito === '' || /\s/.test(pulito)) {
    throw new Error(`Un identificatore ${tipo} non può essere vuoto né contenere spazi.`)
  }
  return [
    ['i', `${prefisso}${pulito}`],
    ['k', prefisso.slice(0, -1)],
  ]
}

/** A positive whole number from a tag, or `undefined`. */
function intero(valore: string | undefined): number | undefined {
  if (valore === undefined) return undefined
  const n = Number(valore)
  return Number.isInteger(n) && n > 0 ? n : undefined
}

function richiediIntero(valore: number | undefined, nome: string): void {
  if (valore !== undefined && (!Number.isInteger(valore) || valore <= 0)) {
    throw new Error(`${nome} deve essere un numero intero positivo: ricevuto ${valore}.`)
  }
}

export const TIPI_EPISODIO = ['full', 'trailer', 'bonus'] as const
export type TipoEpisodio = (typeof TIPI_EPISODIO)[number]

export const TIPI_PODCAST = ['episodic', 'serial'] as const
export type TipoPodcast = (typeof TIPI_PODCAST)[number]

const fileSchema = z.object({ url: z.string(), mime: z.string().optional() })
export type FileAllegato = z.infer<typeof fileSchema>

function leggiFile(event: NostrEvent, nome: string): FileAllegato[] {
  return tagsNamed(event, nome)
    .filter((t) => typeof t[1] === 'string' && t[1] !== '')
    .map((t) => ({ url: t[1] as string, ...(t[2] ? { mime: t[2] } : {}) }))
}

function tagFile(nome: string, file: readonly FileAllegato[]): Tag[] {
  return file
    .filter((f) => f.url.trim() !== '')
    .map((f) => (f.mime ? [nome, f.url.trim(), f.mime] : [nome, f.url.trim()]))
}

const MIME_CAPITOLI = 'application/json+chapters'

/*
 * Beyond NIP-F4.
 *
 * The podcast platforms — Apple, Spotify, Amazon, YouTube — demand things in
 * the RSS feed that NIP-F4 does not provide for: a category, a language, an
 * email to send the ownership verification to, an «explicit» flag, the
 * episodes' duration. The feed is generated by a service from the events, so
 * that data has to sit *in the events*. The convention, shared with the
 * service:
 *
 *   10154  ["category", "News", "Daily News"]   up to three, the first is the primary one
 *          ["language", "it"]                   ISO 639-1
 *          ["email", "owner@…"]                 public, as it already is in the feed
 *          ["content-warning", "…"]             NIP-36, already standard: present = explicit
 *   54     ["duration", "3600"]                 whole seconds, as in NIP-71
 *          ["content-warning", "…"]             the single episode's explicit flag
 *
 * The show's links on the platforms are websites, and NIP-F4 allows more than
 * one: they go in the `website` tags, after the podcast's own site, with no
 * new tags.
 */

/**
 * Kind 54 — a podcast episode (NIP-F4).
 *
 * It is the only standardised audio kind: in the NIP index there is no generic
 * "music track" or "audio file". Whoever wants to publish audio that shows up
 * in social clients uses a note (kind 1) with an `imeta` attachment; kind 54
 * is for when the content really is an episode and you want podcast players to
 * find it.
 *
 * **NIP-F4's model is unusual and worth saying out loud**: every podcast is a
 * *key of its own*, and the episodes are signed by that key directly. By
 * publishing a kind 54 with your personal identity, that identity *becomes*
 * the podcast — there is no intermediate layer. The show's description sits in
 * kind 10154, replaceable, on the same key.
 *
 * A technical difference from the media kinds: the audio is declared with an
 * `audio` tag (url plus an optional MIME type), **not** with `imeta`. There is
 * therefore neither a hash nor a size, and the listener cannot verify that the
 * file is the one published. It is the specification that wants it this way.
 */

export const podcastEpisodeSchema = z.object({
  /** The episode's notes, in Markdown. */
  content: z.string(),
  title: z.string(),
  description: z.string().optional(),
  image: z.string().optional(),
  /** The audio sources, in order. The first is the main one. */
  audio: z.array(z.object({ url: z.string(), mime: z.string().optional() })),
  /** The duration in seconds, when declared: the feed puts it in itunes:duration. */
  duration: z.number().optional(),
  /** Explicit content (NIP-36): the reason, when there is one. */
  contentWarning: z.string().optional(),
  /** The GUID the episode had on another host, from the NIP-73 `i` tag. */
  guidOriginale: z.string().optional(),
  /** The first publication, in unix seconds, when it predates the event. */
  publishedAt: z.number().int().positive().optional(),
  stagione: z.number().int().positive().optional(),
  numero: z.number().int().positive().optional(),
  tipoEpisodio: z.enum(TIPI_EPISODIO).optional(),
  trascrizioni: z.array(fileSchema),
  capitoli: fileSchema.optional(),
  persone: z.array(personaSchema),
  valore: valoreSchema.optional(),
})

export type PodcastEpisodeParsed = z.infer<typeof podcastEpisodeSchema>

export interface PodcastEpisodeInput {
  content?: string
  title: string
  description?: string
  image?: string
  audio: { url: string; mime?: string }[]
  /** Seconds; it gets rounded. */
  duration?: number
  /** Present (even empty) = an explicit episode. */
  contentWarning?: string
  /** The GUID on the old host. Absent for an episode born on NMC: its id is its GUID. */
  guidOriginale?: string
  /** The original publication date, in unix seconds. It cannot be in the future. */
  publishedAt?: number
  stagione?: number
  numero?: number
  tipoEpisodio?: TipoEpisodio
  trascrizioni?: FileAllegato[]
  capitoli?: FileAllegato
  persone?: Persona[]
  valore?: Valore
}

export const podcastEpisodeDefinition = defineKind<PodcastEpisodeParsed, PodcastEpisodeInput>({
  kind: 54,
  name: 'episodio-podcast',
  nip: 'NIP-F4',
  class: 'regular',
  editable: false, // regular: immutable, like a note
  deletable: true,
  schema: podcastEpisodeSchema,
  feed: { eligible: true, requiresMedia: true },
  renderer: 'podcast',

  parse(event) {
    const title = tagValue(event, 'title')
    if (title === undefined) {
      throw new Error(`kind 54 senza tag "title": evento ${event.id}`)
    }

    const description = tagValue(event, 'description')
    const image = tagValue(event, 'image')
    const durata = Number(tagValue(event, 'duration'))
    const avviso = tagsNamed(event, 'content-warning')[0]
    const guidOriginale = leggiIdentificatore(event, PREFISSO_GUID_EPISODIO)
    const publishedAt = intero(tagValue(event, 'published_at'))
    const stagione = intero(tagValue(event, 'season'))
    const numero = intero(tagValue(event, 'episode'))
    const tipo = tagValue(event, 'episode-type')
    const capitoli = leggiFile(event, 'chapters')[0]
    const valore = leggiValore(event)

    return podcastEpisodeSchema.parse({
      content: event.content,
      title,
      ...(description !== undefined ? { description } : {}),
      ...(image !== undefined ? { image } : {}),
      audio: tagsNamed(event, 'audio')
        .filter((t) => typeof t[1] === 'string' && t[1] !== '')
        .map((t) => ({
          url: t[1] as string,
          ...(t[2] ? { mime: t[2] } : {}),
        })),
      ...(Number.isFinite(durata) && durata > 0 ? { duration: durata } : {}),
      ...(avviso ? { contentWarning: avviso[1] ?? '' } : {}),
      ...(guidOriginale ? { guidOriginale } : {}),
      ...(publishedAt ? { publishedAt } : {}),
      ...(stagione ? { stagione } : {}),
      ...(numero ? { numero } : {}),
      // Tolerant like the rest of parse: an unknown type from another client
      // is dropped, not an error.
      ...(tipo && (TIPI_EPISODIO as readonly string[]).includes(tipo)
        ? { tipoEpisodio: tipo as TipoEpisodio }
        : {}),
      trascrizioni: leggiFile(event, 'transcript'),
      ...(capitoli ? { capitoli } : {}),
      persone: leggiPersone(event),
      ...(valore ? { valore } : {}),
    })
  },

  build(input, ctx) {
    if (input.title.trim() === '') {
      throw new Error('Un episodio ha bisogno di un titolo: e’ come lo si trova in un lettore.')
    }
    if (input.publishedAt !== undefined) {
      richiediIntero(input.publishedAt, 'La data di prima pubblicazione')
      if (input.publishedAt > ctx.now) {
        throw new Error('La data di prima pubblicazione non può essere nel futuro.')
      }
    }
    richiediIntero(input.stagione, 'La stagione')
    richiediIntero(input.numero, 'Il numero dell’episodio')
    if (input.tipoEpisodio !== undefined && !TIPI_EPISODIO.includes(input.tipoEpisodio)) {
      throw new Error(`Tipo di episodio non ammesso: «${input.tipoEpisodio}».`)
    }
    // Mandatory under NIP-F4. The `parse` accepts it missing — other people's
    // events — but what gets published from here has to conform.
    if (!input.description || input.description.trim() === '') {
      throw new Error(
        'Un episodio ha bisogno di una descrizione: i lettori di podcast la mostrano sotto il titolo.',
      )
    }
    if (input.audio.length === 0) {
      throw new Error(
        'Un episodio senza sorgente audio non e’ ascoltabile. Per un testo senza audio usa una nota o un articolo.',
      )
    }

    return {
      kind: 54,
      content: input.content ?? '',
      tags: [
        ['title', input.title.trim()],
        ['description', input.description.trim()],
        ...optionalTag('image', input.image),
        // The MIME type is optional per the specification, but without it the
        // player has to guess it from the URL's extension.
        ...input.audio.map((a) => (a.mime ? ['audio', a.url, a.mime] : ['audio', a.url])),
        ...(input.duration && input.duration > 0
          ? [['duration', String(Math.round(input.duration))]]
          : []),
        ...(input.contentWarning !== undefined ? [['content-warning', input.contentWarning]] : []),
        ...tagIdentificatore(PREFISSO_GUID_EPISODIO, input.guidOriginale, 'di episodio'),
        // The date the episode first went out. `created_at` stays the true
        // moment of signing: the event does not lie about when it was born.
        ...(input.publishedAt !== undefined ? [['published_at', String(input.publishedAt)]] : []),
        ...(input.stagione !== undefined ? [['season', String(input.stagione)]] : []),
        ...(input.numero !== undefined ? [['episode', String(input.numero)]] : []),
        ...optionalTag('episode-type', input.tipoEpisodio),
        ...tagFile('transcript', input.trascrizioni ?? []),
        ...tagFile('chapters', input.capitoli ? [{ mime: MIME_CAPITOLI, ...input.capitoli }] : []),
        ...tagPersone(input.persone),
        ...tagValore(input.valore),
      ],
      created_at: ctx.now,
    }
  },
})

/**
 * Kind 10154 — the podcast's description (NIP-F4).
 *
 * Replaceable, on the podcast's key. Podcast players read this one and can
 * ignore kind 0 entirely: it is the *show's* card, not the person's, even when
 * the two keys are the same.
 */
export const podcastMetadataSchema = z.object({
  title: z.string(),
  description: z.string().optional(),
  image: z.string().optional(),
  websites: z.array(z.string()),
  /** The declared authors, with their role: `host`, `cohost` or `editor`. */
  authors: z.array(z.object({ pubkey: z.string(), role: z.string().optional() })),
  /** The Apple categories; the first is the primary one. */
  categories: z.array(z.object({ principale: z.string(), sotto: z.string().optional() })),
  language: z.string().optional(),
  email: z.string().optional(),
  contentWarning: z.string().optional(),
  /** The show's identity (`podcast:guid`), from the NIP-73 `i` tag: written once, never recomputed. */
  podcastGuid: z.string().optional(),
  /** The feed's stable public address (tag `feed`). */
  feedUrl: z.string().optional(),
  /** The name the feed signs as (`itunes:author`), when it differs from the profile's. */
  autore: z.string().optional(),
  tipo: z.enum(TIPI_PODCAST).optional(),
  valore: valoreSchema.optional(),
  persone: z.array(personaSchema),
  finanziamenti: z.array(z.object({ url: z.string(), testo: z.string().optional() })),
})

export type PodcastMetadataParsed = z.infer<typeof podcastMetadataSchema>

export interface PodcastMetadataInput {
  title: string
  description?: string
  image?: string
  websites?: string[]
  authors?: { pubkey: string; role?: string }[]
  categories?: { principale: string; sotto?: string }[]
  language?: string
  email?: string
  /** Present (even empty) = an explicit podcast. */
  contentWarning?: string
  podcastGuid?: string
  feedUrl?: string
  autore?: string
  tipo?: TipoPodcast
  valore?: Valore
  persone?: Persona[]
  finanziamenti?: { url: string; testo?: string }[]
}

/** True for an absolute http(s) URL. */
function httpUrl(valore: string): boolean {
  try {
    const u = new URL(valore)
    return u.protocol === 'https:' || u.protocol === 'http:'
  } catch {
    return false
  }
}

export const podcastMetadataDefinition = defineKind<PodcastMetadataParsed, PodcastMetadataInput>({
  kind: 10154,
  name: 'descrizione-podcast',
  nip: 'NIP-F4',
  class: 'replaceable',
  editable: true,
  deletable: true,
  schema: podcastMetadataSchema,
  feed: { eligible: false },
  renderer: 'podcast-show',

  parse(event) {
    const title = tagValue(event, 'title')
    if (title === undefined) {
      throw new Error(`kind 10154 senza tag "title": evento ${event.id}`)
    }
    const description = tagValue(event, 'description')
    const image = tagValue(event, 'image')

    const language = tagValue(event, 'language')
    const email = tagValue(event, 'email')
    const avviso = tagsNamed(event, 'content-warning')[0]
    const podcastGuid = leggiIdentificatore(event, PREFISSO_GUID_PODCAST)
    const feedUrl = tagValue(event, 'feed')
    const autore = tagValue(event, 'author')
    const tipo = tagValue(event, 'type')
    const valore = leggiValore(event)

    return podcastMetadataSchema.parse({
      title,
      ...(description !== undefined ? { description } : {}),
      ...(image !== undefined ? { image } : {}),
      websites: tagsNamed(event, 'website')
        .map((t) => t[1])
        .filter((u): u is string => typeof u === 'string' && u !== ''),
      authors: tagsNamed(event, 'p')
        .filter((t) => typeof t[1] === 'string')
        .map((t) => ({ pubkey: t[1] as string, ...(t[2] ? { role: t[2] } : {}) })),
      // Tolerant: a category Apple does not know is read all the same; it is
      // the build that refuses it when we are the ones writing it.
      categories: tagsNamed(event, 'category')
        .filter((t) => typeof t[1] === 'string' && t[1] !== '')
        .map((t) => ({ principale: t[1] as string, ...(t[2] ? { sotto: t[2] } : {}) })),
      ...(language ? { language } : {}),
      ...(email ? { email } : {}),
      ...(avviso ? { contentWarning: avviso[1] ?? '' } : {}),
      ...(podcastGuid ? { podcastGuid } : {}),
      ...(feedUrl ? { feedUrl } : {}),
      ...(autore ? { autore } : {}),
      ...(tipo && (TIPI_PODCAST as readonly string[]).includes(tipo)
        ? { tipo: tipo as TipoPodcast }
        : {}),
      ...(valore ? { valore } : {}),
      persone: leggiPersone(event),
      finanziamenti: tagsNamed(event, 'funding')
        .filter((t) => typeof t[1] === 'string' && t[1] !== '')
        .map((t) => ({ url: t[1] as string, ...(t[2] ? { testo: t[2] } : {}) })),
    })
  },

  build(input, ctx) {
    if (input.title.trim() === '') {
      throw new Error('Il podcast ha bisogno di un titolo.')
    }
    // The image and the description are mandatory under NIP-F4: they are what
    // a podcast player shows in the list of shows. The `parse` stays tolerant
    // with other people's cards.
    if (!input.description || input.description.trim() === '') {
      throw new Error('La scheda del podcast ha bisogno di una descrizione.')
    }
    if (!input.image || input.image.trim() === '') {
      throw new Error('La scheda del podcast ha bisogno di un’immagine di copertina.')
    }
    const categorie = (input.categories ?? []).filter((c) => c.principale.trim() !== '')
    if (categorie.length > MAX_CATEGORIE) {
      throw new Error(`Apple accetta al massimo ${MAX_CATEGORIE} categorie.`)
    }
    for (const c of categorie) {
      if (!isCategoriaApple(c)) {
        throw new Error(
          `«${c.sotto ? `${c.principale} / ${c.sotto}` : c.principale}» non e’ una categoria di Apple Podcasts.`,
        )
      }
    }
    const lingua = input.language?.trim().toLowerCase()
    if (lingua && !/^[a-z]{2}(-[a-z]{2})?$/.test(lingua)) {
      throw new Error('La lingua va scritta come codice ISO 639-1, per esempio «it» o «en».')
    }
    const email = input.email?.trim()
    if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      throw new Error('L’email non sembra un indirizzo valido.')
    }
    const feedUrl = input.feedUrl?.trim()
    if (feedUrl && !indirizzoFeedAmmesso(feedUrl)) {
      throw new Error('L’indirizzo stabile del feed deve essere un URL https completo.')
    }
    if (input.tipo !== undefined && !TIPI_PODCAST.includes(input.tipo)) {
      throw new Error(`Tipo di podcast non ammesso: «${input.tipo}».`)
    }
    const finanziamenti = (input.finanziamenti ?? []).filter((f) => f.url.trim() !== '')
    for (const f of finanziamenti) {
      if (!httpUrl(f.url.trim())) {
        throw new Error(`Il link di sostegno «${f.url}» non è un indirizzo web valido.`)
      }
    }

    return {
      kind: 10154,
      content: '',
      tags: [
        ['title', input.title.trim()],
        ['description', input.description.trim()],
        ['image', input.image.trim()],
        ...repeatedTags('website', input.websites ?? []),
        ...categorie.map((c) =>
          c.sotto ? ['category', c.principale, c.sotto] : ['category', c.principale],
        ),
        ...optionalTag('language', lingua),
        ...optionalTag('email', email),
        ...(input.contentWarning !== undefined ? [['content-warning', input.contentWarning]] : []),
        // The role declared here proves nothing on its own: NIP-F4 asks for it
        // to be cross-checked against the kind 10064 published by the author
        // themselves, because a podcast can claim anyone at all.
        ...(input.authors ?? []).map((a) => (a.role ? ['p', a.pubkey, a.role] : ['p', a.pubkey])),
        ...tagIdentificatore(PREFISSO_GUID_PODCAST, input.podcastGuid, 'di podcast'),
        ...optionalTag('feed', feedUrl),
        ...optionalTag('author', input.autore),
        ...optionalTag('type', input.tipo),
        ...tagValore(input.valore),
        ...tagPersone(input.persone),
        ...finanziamenti.map((f) =>
          f.testo?.trim() ? ['funding', f.url.trim(), f.testo.trim()] : ['funding', f.url.trim()],
        ),
      ],
      created_at: ctx.now,
    }
  },
})

/**
 * Kind 10064 — the podcasts a person is an author of (NIP-F4).
 *
 * It is the other half of the circle: the podcast's card (10154) says who the
 * authors are with a `p` tag, but «a podcast can claim anyone at all». The
 * 10064 is published by **the author**, on their key, and names the podcasts:
 * only when the two declarations agree is the link credible.
 *
 * Replaceable: there is a single list per person, and republishing it replaces
 * it.
 */
export const authoredPodcastsSchema = z.object({
  /** The podcasts' keys, in hexadecimal. */
  podcasts: z.array(z.string()),
})

export type AuthoredPodcastsParsed = z.infer<typeof authoredPodcastsSchema>

export interface AuthoredPodcastsInput {
  podcasts: string[]
}

export const authoredPodcastsDefinition = defineKind<AuthoredPodcastsParsed, AuthoredPodcastsInput>(
  {
    kind: 10064,
    name: 'podcast-di-cui-sono-autore',
    nip: 'NIP-F4',
    class: 'replaceable',
    editable: true,
    deletable: true,
    schema: authoredPodcastsSchema,
    feed: { eligible: false },
    renderer: 'podcast-authored',

    parse(event) {
      return authoredPodcastsSchema.parse({
        podcasts: tagsNamed(event, 'p')
          .map((t) => t[1])
          .filter((p): p is string => typeof p === 'string' && /^[0-9a-f]{64}$/.test(p)),
      })
    },

    build(input, ctx) {
      // No duplicates and no blanks: a list that repeats a key says nothing
      // more, and a malformed key is not a podcast.
      const podcasts = [...new Set(input.podcasts.map((p) => p.trim().toLowerCase()))].filter((p) =>
        /^[0-9a-f]{64}$/.test(p),
      )
      if (podcasts.length === 0) {
        throw new Error(
          'La lista dei podcast di cui sei autore e’ vuota: per toglierti da tutti, cancella l’evento invece di pubblicarne uno vuoto.',
        )
      }
      return {
        kind: 10064,
        content: '',
        tags: podcasts.map((p) => ['p', p]),
        created_at: ctx.now,
      }
    },
  },
)
