import { NostrConnectProvider, PrivateKeySigner, type NostrPool } from 'applesauce-signers'

import type { SecretKey } from '../identity/keys.js'
import type { Firmatario, RichiestaFirma } from './types.js'

/**
 * The signing desk: the side of NIP-46 that holds the key.
 *
 * It listens on a relay, receives encrypted requests and answers with signed
 * events. It is what is usually called a *bunker*, and it is normally a
 * service of its own; here it lives inside the client, so that keeping this
 * page open is enough to have the podcast signed without entrusting the key to
 * anyone.
 *
 * ## Two keys, not one
 *
 * NIP-46 distinguishes the `remote-signer-pubkey` from the `user-pubkey`, and
 * the distinction matters here. The **transport** — the NIP-44 encryption of
 * the requests, the address written in the URI — uses a dedicated key; the
 * identity's key steps in only to sign the approved events. Two properties
 * follow that are worth the complication: the desk works even when the
 * identity lives in an extension that does not expose NIP-44, and whoever
 * stole the transport key could impersonate the desk's *address*, never the
 * identity that signs.
 *
 * For the same reason the transport key has to be kept: regenerating it at
 * every start would change the address, and every delegation granted would
 * stop working.
 *
 * ## What the desk does not know
 *
 * The `pubkey` of whoever asks is the **session's**, generated by their
 * client: it is not their identity on Nostr and it does not say who they
 * really are. A desk authenticates nobody — it authorizes whoever holds the
 * address, which contains a secret. Manual approval is therefore the only
 * check that counts, and that is why it cannot be bypassed here.
 */

export interface OpzioniBanco {
  /** An already open pool. Its lifecycle stays with the caller. */
  pool: NostrPool
  /** The relays the desk and the requester meet on: both have to reach them. */
  relays: string[]
  /** Who really signs: the key of the identity that will appear in the events. */
  identita: Firmatario
  /** The transport key, kept between sessions so the address does not change. */
  chiaveTrasporto: SecretKey
  /** The `bunker://` address's secret: it authorizes the first connection. */
  segreto: string
  /**
   * The only kinds the desk agrees to sign.
   *
   * It is not a detail of convenience: without this list whoever obtains a
   * delegation for the episodes could have any note at all signed, and the
   * signature would count as the holder's. The kinds not listed are turned
   * down without even disturbing whoever approves.
   */
  kindsConsentiti: readonly number[]
  /** The human judgement on every admissible request. */
  approva(richiesta: RichiestaFirma): Promise<boolean>
  /** Announces that a requester has connected. */
  onCollegato?: (cliente: string) => void
}

export interface Banco {
  /** The address to hand to whoever will ask for the signatures. It contains the secret. */
  uri: string
  /** The transport public key: the desk's address, not the identity that signs. */
  trasporto: string
  /** Who is connected now, when somebody is. */
  cliente(): string | null
  ferma(): Promise<void>
}

/**
 * Opens the desk and keeps listening until it is stopped.
 *
 * It serves **one requester at a time**: the library refuses a second
 * connection while the first is active. Two collaborators need two desks with
 * distinct transport keys — which also has the merit of letting you revoke one
 * without touching the other.
 */
export async function avviaBanco(opzioni: OpzioniBanco): Promise<Banco> {
  if (opzioni.relays.length === 0) {
    throw new Error('Il banco ha bisogno di almeno un relay su cui farsi trovare.')
  }
  if (opzioni.kindsConsentiti.length === 0) {
    throw new Error('Un banco che non consente alcun kind non firmerebbe mai nulla.')
  }

  const trasporto = new PrivateKeySigner(opzioni.chiaveTrasporto)
  const consentiti = new Set(opzioni.kindsConsentiti)

  const provider = new NostrConnectProvider({
    pool: opzioni.pool,
    relays: [...opzioni.relays],
    signer: trasporto,
    bunkerSecret: opzioni.segreto,

    /*
     * The identity is exposed to the provider with the only two methods that
     * are needed. NIP-46 also provides `nip04_*` and `nip44_*`, that is
     * encrypting and **decrypting** with the holder's key: a requester could
     * have the encrypted drafts or the direct messages of whoever keeps the
     * desk opened for them. The encryption requests are turned down just
     * below, but here the methods do not exist at all — a mistake in the
     * policy would not be enough to expose them.
     */
    upstream: {
      getPublicKey: () => opzioni.identita.pubkey(),
      signEvent: (template) => opzioni.identita.firma(template),
    },

    onSignEvent: async (template, cliente) => {
      if (!consentiti.has(template.kind)) return false
      return opzioni.approva({ cliente, kind: template.kind, template: { ...template } })
    },

    // Encrypting and decrypting with the holder's key: never, for anyone.
    onNip04Encrypt: () => false,
    onNip04Decrypt: () => false,
    onNip44Encrypt: () => false,
    onNip44Decrypt: () => false,

    ...(opzioni.onCollegato ? { onClientConnect: opzioni.onCollegato } : {}),
  })

  await provider.start()
  const uri = await provider.getBunkerURI()

  return {
    uri,
    trasporto: await trasporto.getPublicKey(),
    cliente: () => provider.client ?? null,
    ferma: () => provider.stop(),
  }
}
